from functools import lru_cache

import torch

_GROUP_SIZE = 256
"""Threads per threadgroup; each thread evaluates one element."""

_KERNEL = {
    torch.float32: "log_ndtr_f32",
    torch.float16: "log_ndtr_f16",
    torch.bfloat16: "log_ndtr_bf16",
}
"""One entry point per storage dtype."""


@lru_cache(maxsize=1)
def _library():
    return torch.mps.compile_shader(_SOURCE)


def _launch(source, destination):
    count = source.numel()
    getattr(_library(), _KERNEL[destination.dtype])(
        source, destination, count, threads=count, group_size=_GROUP_SIZE
    )


def _promoted_dtype(self):
    return self.dtype if self.dtype in _KERNEL else torch.float32


def _kernel_input(self):
    """What the kernel reads: ``self`` in a float dtype, contiguous."""
    if self.dtype in _KERNEL:
        return self.contiguous()
    return self.to(torch.float32).contiguous()


def _check(self):
    if self.device.type != "mps":
        raise ValueError(f"Metal kernels need tensors on the mps device, got {self.device}")
    if self.is_complex():
        raise NotImplementedError(f'"log_ndtr_mps" not implemented for {self.dtype}')


def log_ndtr(self):
    """``aten::special_log_ndtr`` for MPS: same dtype, shape and autograd as CPU."""
    _check(self)
    source = _kernel_input(self)
    out = torch.empty(self.shape, dtype=source.dtype, device=source.device)
    if source.numel():
        _launch(source, out)
    return out


def log_ndtr_out(self, *, out):
    """``aten::special_log_ndtr.out``: writes into ``out`` and returns it."""
    if out.device != self.device:
        raise RuntimeError(
            "Expected all tensors to be on the same device, but found at least "
            f"two devices, {self.device} and {out.device}!"
        )
    _check(self)
    if out.shape != self.shape:
        out.resize_(self.shape)
    dtype = _promoted_dtype(self)
    if not torch.can_cast(dtype, out.dtype):
        raise RuntimeError(
            f"result type {dtype} can't be cast to the desired output type {out.dtype}"
        )
    if out.dtype == dtype and out.is_contiguous():
        source = _kernel_input(self)
        shared = source.untyped_storage().data_ptr() == out.untyped_storage().data_ptr()
        # An in-place elementwise write is safe when the two pointers are equal;
        # offset views over one storage are not.
        if not (shared and source.data_ptr() != out.data_ptr()):
            if source.numel():
                _launch(source, out)
            return out
    return out.copy_(log_ndtr(self))


OVERLAYS = (
    ("special_log_ndtr", log_ndtr),
    ("special_log_ndtr.out", log_ndtr_out),
)
