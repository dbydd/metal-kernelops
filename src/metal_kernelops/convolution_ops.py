"""MPS kernels for the six legacy ``slow_conv*`` aten entry points.

torch 2.14.1 has a CPU kernel for each of them and no MPS kernel. A direct call
on an MPS tensor raises ``NotImplementedError``; ``slow_conv_transpose2d`` gives
the same error one level down, because its default overload is a decomposition
that lands on the missing structured ``.out`` overload.

The Metal convolution kernels already exist as ``aten::_mps_convolution`` and
``aten::_mps_convolution_transpose``. These bodies are the native convolution
operators that reach them, so nothing leaves the GPU and nothing calls the op
being overlaid. Their autograd formulas are the generated ones, which call
``aten::convolution_backward``; gradients are therefore the same grads the CPU
kernels produce, with no extra code here.

Entry point per op, chosen by measurement (see ``measured/convolution.json``):

* forward, not transposed: ``aten::_mps_convolution``, the Metal kernel itself.
  It skips ``convolution``'s ``ConvParams``/backend-selection layer: 0.8-1.3 us
  less enqueue per call, bitwise identical output on fp32/fp16/bf16, on
  channels-last, on non-contiguous, on expanded and on empty inputs.
* forward, transposed: ``aten::convolution``. Calling
  ``_mps_convolution_transpose`` directly costs 7-9 us *more* on the same work -
  it does not take the bias, so it also needs a separate ``add_``.
* backward: ``aten::convolution_backward``, the only entry that does the
  grad-input/grad-weight/grad-bias selection in one call.

``_mps_convolution`` does not validate the bias shape, and a bias with the wrong
number of elements does not raise inside Metal: it aborts the process. The check
that ``convolution`` would have run is repeated in ``_check_bias``.

The shapes are the legacy ones, which are not the ``torch.nn.functional``
shapes:

* ``slow_conv3d_forward`` requires a 5-D input; groups are fixed at 1.
* ``slow_conv_dilated2d`` / ``slow_conv_dilated3d`` accept an unbatched input
  and return an unbatched output.
* ``slow_conv_transpose2d`` accepts an unbatched input and returns a *batched*
  output, batch size 1: its structured meta function force-batches.
* ``slow_conv_transpose3d`` accepts an unbatched input and returns an unbatched
  output.

``_slow_conv2d_backward`` is itself a backward op, so both of its overloads are
implemented: ``output_mask`` returns undefined tensors for masked-off entries,
``grad_input`` writes the caller's tensors.

Importing this module registers and compiles nothing; ``accelerator.install``
owns registration. Each entry in ``OVERLAYS`` is ``(aten overload name, kernel)``.
The ``.out`` overloads that have their own CPU kernel are included; the
autogenerated ``slow_conv_dilated2d.out`` / ``slow_conv_dilated3d.out`` reach the
default overload, so they need no entry.

``slow_conv3d_forward.output`` computes into the caller's tensor through
``aten::_mps_convolution.out``, which resizes a zero-element output itself. A
``Tensor(a!)`` argument cannot be rebound, so the only way to survive a copy
would be to allocate the output and copy it afterwards, and that copy costs
7.7 us per call on these shapes. A caller tensor that already holds elements
and has the wrong shape still takes that copy path, and PyTorch warns about the
resize that replaces it.

The ``.out`` overload of ``slow_conv_transpose2d`` / ``slow_conv_transpose3d``
computes with ``aten::convolution`` and copies into the caller's tensor. The
native out= forms (``convolution.out``, ``_mps_convolution_transpose.out``) are
``CompositeExplicitAutograd`` allocate-then-copy, measured 4-12 us slower than
the explicit resize-and-copy below.

Limits that come from the native kernels, not from these bodies:

* ``slow_conv_transpose3d`` has no fp16/bf16 Metal kernel; fp32 only.
* An unbatched input works in the forward of every op above, but backward needs
  a batched input for ``slow_conv_transpose2d``: its generated autograd formula
  calls ``aten::convolution_backward`` with the 3-D input, and that op rejects
  unbatched input on CPU and MPS alike. The legacy CPU forward keeps a separate
  unbatched backward, which the shared formula does not reproduce.
* ``slow_conv_dilated2d`` / ``slow_conv_dilated3d`` unbatched backward fails on
  CPU as well, for the same reason.
* A kernel larger than the padded input: the CPU kernels raise, the Metal kernel
  returns a zero-sized output instead, so the two disagree on that input.
"""

import torch

_convolution = torch.ops.aten.convolution
_convolution_backward = torch.ops.aten.convolution_backward
_mps_convolution = torch.ops.aten._mps_convolution

_UNIT2 = (1, 1)
_UNIT3 = (1, 1, 1)
_ZERO2 = (0, 0)
_ZERO3 = (0, 0, 0)

__all__ = ["OVERLAYS"]


def _reject_params(name, rank, kernel_size, stride, padding, dilation):
    for label, value in (
        ("kernel_size", kernel_size),
        ("stride", stride),
        ("padding", padding),
        ("dilation", dilation),
    ):
        if len(value) != rank:
            raise ValueError(f"{name}: {label} must have {rank} elements, got {list(value)}")
    for label, value in (("kernel_size", kernel_size), ("stride", stride), ("dilation", dilation)):
        if min(value) <= 0:
            raise ValueError(f"{name}: {label} must be positive, got {list(value)}")
    raise ValueError(f"{name}: padding must be non-negative, got {list(padding)}")


def _check2(name, kernel_size, stride, padding, dilation):
    """The legacy argument checks the native op does not repeat, rank 2.

    Unrolled: the loop and ``min()`` calls of the generic form cost 0.17 us of
    the ~7 us this module spends per call. The length tests stay in front of the
    index reads inside the same ``or`` chain, so a short argument cannot raise
    IndexError before it reaches the error path.
    """
    if (
        len(kernel_size) != 2
        or len(stride) != 2
        or len(padding) != 2
        or len(dilation) != 2
        or kernel_size[0] <= 0
        or kernel_size[1] <= 0
        or stride[0] <= 0
        or stride[1] <= 0
        or dilation[0] <= 0
        or dilation[1] <= 0
        or padding[0] < 0
        or padding[1] < 0
    ):
        _reject_params(name, 2, kernel_size, stride, padding, dilation)


def _check3(name, kernel_size, stride, padding, dilation):
    if (
        len(kernel_size) != 3
        or len(stride) != 3
        or len(padding) != 3
        or len(dilation) != 3
        or kernel_size[0] <= 0
        or kernel_size[1] <= 0
        or kernel_size[2] <= 0
        or stride[0] <= 0
        or stride[1] <= 0
        or stride[2] <= 0
        or dilation[0] <= 0
        or dilation[1] <= 0
        or dilation[2] <= 0
        or padding[0] < 0
        or padding[1] < 0
        or padding[2] < 0
    ):
        _reject_params(name, 3, kernel_size, stride, padding, dilation)


def _reject_weight(name, rank, weight, kernel_size):
    if weight.dim() != rank + 2:
        raise ValueError(
            f"{name}: weight must be {rank + 2}-D, got {weight.dim()}-D {list(weight.shape)}"
        )
    raise ValueError(
        f"{name}: kernel_size {list(kernel_size)} does not match weight spatial "
        f"dims {list(weight.shape[2:])}"
    )


def _check_weight2(name, weight, kernel_size):
    shape = weight.shape
    if len(shape) != 4 or shape[2] != kernel_size[0] or shape[3] != kernel_size[1]:
        _reject_weight(name, 2, weight, kernel_size)


def _check_weight3(name, weight, kernel_size):
    shape = weight.shape
    if (
        len(shape) != 5
        or shape[2] != kernel_size[0]
        or shape[3] != kernel_size[1]
        or shape[4] != kernel_size[2]
    ):
        _reject_weight(name, 3, weight, kernel_size)


def _check_bias(weight, bias):
    """``_mps_convolution`` has no bias check: a mismatched bias aborts in Metal."""
    if bias is None:
        return
    shape = bias.shape
    if len(shape) != 1 or shape[0] != weight.shape[0]:
        raise RuntimeError(
            f"Given weight of size {list(weight.shape)}, expected bias to be 1-dimensional "
            f"with {weight.shape[0]} elements, but got bias of size {list(shape)} instead"
        )


def _reject_output_padding(name, output_padding, stride, dilation):
    for value, s, d in zip(output_padding, stride, dilation):
        if value < 0 or (value >= s and value >= d):
            raise ValueError(
                f"{name}: output_padding must be non-negative and smaller than stride "
                f"or dilation, got {list(output_padding)}"
            )


def _check_output_padding(name, output_padding, stride, dilation):
    # Zero is always valid against the positive stride and dilation that
    # _check2/_check3 have already enforced, so the loop only runs for a caller
    # that actually padded the output.
    if any(output_padding):
        _reject_output_padding(name, output_padding, stride, dilation)


def _conv3d_checked(input, weight, kernel_size, bias, stride, padding):
    if (
        len(kernel_size) != 3
        or len(stride) != 3
        or len(padding) != 3
        or kernel_size[0] <= 0
        or kernel_size[1] <= 0
        or kernel_size[2] <= 0
        or stride[0] <= 0
        or stride[1] <= 0
        or stride[2] <= 0
        or padding[0] < 0
        or padding[1] < 0
        or padding[2] < 0
    ):
        _reject_params("slow_conv3d_forward", 3, kernel_size, stride, padding, _UNIT3)
    if input.dim() != 5:
        raise ValueError(
            f"slow_conv3d_forward: input must be 5-D, got {input.dim()}-D {list(input.shape)}"
        )
    _check_weight3("slow_conv3d_forward", weight, kernel_size)
    _check_bias(weight, bias)


def _slow_conv3d_forward(input, weight, kernel_size, bias, stride, padding):
    _conv3d_checked(input, weight, kernel_size, bias, stride, padding)
    return _mps_convolution(input, weight, bias, padding, stride, _UNIT3, 1)


def _slow_conv3d_forward_output(input, weight, kernel_size, bias, stride, padding, *, output):
    _conv3d_checked(input, weight, kernel_size, bias, stride, padding)
    # The kernel resizes a zero-element output itself; the copy the alternative
    # path would need costs 7.7 us per call.
    if not output.numel():
        output.resize_(0)
    return _mps_convolution(input, weight, bias, padding, stride, _UNIT3, 1, out=output)


def _slow_conv_dilated2d(
    input, weight, kernel_size, bias=None, stride=_UNIT2, padding=_ZERO2, dilation=_UNIT2
):
    _check2("slow_conv_dilated2d", kernel_size, stride, padding, dilation)
    _check_weight2("slow_conv_dilated2d", weight, kernel_size)
    _check_bias(weight, bias)
    if input.dim() == 3:
        return _mps_convolution(
            input.unsqueeze(0), weight, bias, padding, stride, dilation, 1
        ).squeeze(0)
    if input.dim() != 4:
        raise ValueError(f"slow_conv_dilated2d: input must be 3-D or 4-D, got {input.dim()}-D")
    return _mps_convolution(input, weight, bias, padding, stride, dilation, 1)


def _slow_conv_dilated3d(
    input, weight, kernel_size, bias=None, stride=_UNIT3, padding=_ZERO3, dilation=_UNIT3
):
    _check3("slow_conv_dilated3d", kernel_size, stride, padding, dilation)
    _check_weight3("slow_conv_dilated3d", weight, kernel_size)
    _check_bias(weight, bias)
    if input.dim() == 4:
        return _mps_convolution(
            input.unsqueeze(0), weight, bias, padding, stride, dilation, 1
        ).squeeze(0)
    if input.dim() != 5:
        raise ValueError(f"slow_conv_dilated3d: input must be 4-D or 5-D, got {input.dim()}-D")
    return _mps_convolution(input, weight, bias, padding, stride, dilation, 1)


def _slow_conv_transpose2d(
    input,
    weight,
    kernel_size,
    bias=None,
    stride=_UNIT2,
    padding=_ZERO2,
    output_padding=_ZERO2,
    dilation=_UNIT2,
):
    _check2("slow_conv_transpose2d", kernel_size, stride, padding, dilation)
    _check_weight2("slow_conv_transpose2d", weight, kernel_size)
    _check_output_padding("slow_conv_transpose2d", output_padding, stride, dilation)
    if input.dim() == 3:
        input = input.unsqueeze(0)
    elif input.dim() != 4:
        raise ValueError(f"slow_conv_transpose2d: input must be 3-D or 4-D, got {input.dim()}-D")
    # The structured meta function force-batches the input and never squeezes it
    # back, so an unbatched call returns a batch of one.
    return _convolution(
        input, weight, bias, stride, padding, dilation, True, output_padding, 1
    )


def _slow_conv_transpose2d_out(
    input,
    weight,
    kernel_size,
    bias=None,
    stride=_UNIT2,
    padding=_ZERO2,
    output_padding=_ZERO2,
    dilation=_UNIT2,
    *,
    out,
):
    result = _slow_conv_transpose2d(
        input, weight, kernel_size, bias, stride, padding, output_padding, dilation
    )
    if result.shape != out.shape:
        out.resize_(result.shape)
    return out.copy_(result)


def _slow_conv_transpose3d(
    input,
    weight,
    kernel_size,
    bias=None,
    stride=_UNIT3,
    padding=_ZERO3,
    output_padding=_ZERO3,
    dilation=_UNIT3,
):
    _check3("slow_conv_transpose3d", kernel_size, stride, padding, dilation)
    _check_weight3("slow_conv_transpose3d", weight, kernel_size)
    _check_output_padding("slow_conv_transpose3d", output_padding, stride, dilation)
    if input.dim() == 4:
        return _convolution(
            input.unsqueeze(0), weight, bias, stride, padding, dilation, True, output_padding, 1
        ).squeeze(0)
    if input.dim() != 5:
        raise ValueError(f"slow_conv_transpose3d: input must be 4-D or 5-D, got {input.dim()}-D")
    return _convolution(input, weight, bias, stride, padding, dilation, True, output_padding, 1)


def _slow_conv_transpose3d_out(
    input,
    weight,
    kernel_size,
    bias=None,
    stride=_UNIT3,
    padding=_ZERO3,
    output_padding=_ZERO3,
    dilation=_UNIT3,
    *,
    out,
):
    result = _slow_conv_transpose3d(
        input, weight, kernel_size, bias, stride, padding, output_padding, dilation
    )
    if result.shape != out.shape:
        out.resize_(result.shape)
    return out.copy_(result)


def _slow_conv2d_backward_output_mask(
    grad_output, input, weight, kernel_size, stride, padding, output_mask
):
    if len(kernel_size) != 2 or len(stride) != 2 or len(padding) != 2:
        raise ValueError(
            "_slow_conv2d_backward: kernel_size, stride and padding must have 2 elements"
        )
    if weight.dim() == 2:
        flat = True
        weight_4d = weight.reshape(weight.shape[0], -1, kernel_size[0], kernel_size[1])
    else:
        flat = False
        _check_weight2("_slow_conv2d_backward", weight, kernel_size)
        weight_4d = weight
    grad_input, grad_weight, grad_bias = _convolution_backward(
        grad_output,
        input,
        weight_4d,
        (weight_4d.shape[0],),
        stride,
        padding,
        _UNIT2,
        False,
        _ZERO2,
        1,
        output_mask,
    )
    if flat and grad_weight is not None:
        grad_weight = grad_weight.reshape(weight.shape)
    return grad_input, grad_weight, grad_bias


def _slow_conv2d_backward_grad_input(
    grad_output,
    input,
    weight,
    kernel_size,
    stride,
    padding,
    grad_input,
    grad_weight,
    grad_bias,
):
    grads = _slow_conv2d_backward_output_mask(
        grad_output, input, weight, kernel_size, stride, padding, [True, True, True]
    )
    outs = []
    for out, grad in zip((grad_input, grad_weight, grad_bias), grads):
        if out is not None and grad is not None:
            if out.shape != grad.shape:
                out.resize_(grad.shape)
            out.copy_(grad)
        outs.append(out)
    return tuple(outs)


OVERLAYS = (
    ("slow_conv3d_forward", _slow_conv3d_forward),
    ("slow_conv3d_forward.output", _slow_conv3d_forward_output),
    ("slow_conv_dilated2d", _slow_conv_dilated2d),
    ("slow_conv_dilated3d", _slow_conv_dilated3d),
    ("slow_conv_transpose2d", _slow_conv_transpose2d),
    ("slow_conv_transpose2d.out", _slow_conv_transpose2d_out),
    ("slow_conv_transpose3d", _slow_conv_transpose3d),
    ("slow_conv_transpose3d.out", _slow_conv_transpose3d_out),
    ("_slow_conv2d_backward.output_mask", _slow_conv2d_backward_output_mask),
    ("_slow_conv2d_backward.grad_input", _slow_conv2d_backward_grad_input),
)
